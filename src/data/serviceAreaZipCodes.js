/** True if the given 5-digit ZIP string is in the approved service area. */
export function isApprovedServiceZip(zip) {
  return Object.prototype.hasOwnProperty.call(serviceAreaByZip, zip);
}

/** Returns { city, state, county } for an approved ZIP, or null if not approved. */
export function getServiceAreaForZip(zip) {
  return serviceAreaByZip[zip] || null;
}

// The source CSV's county spelling is a raw mailing-name transcription
// (e.g. "Mchenry", "La Salle") and is left untouched in serviceAreaByZip
// above so the approved data itself is never silently edited. This map is
// purely a *display* correction to the standard/official Illinois county
// name, used only when rendering county names to a page.
const COUNTY_DISPLAY_NAMES = {
  'Cook': 'Cook',
  'Dekalb': 'DeKalb',
  'Dupage': 'DuPage',
  'Grundy': 'Grundy',
  'Kane': 'Kane',
  'Kankakee': 'Kankakee',
  'Kendall': 'Kendall',
  'La Salle': 'LaSalle',
  'Lake': 'Lake',
  'Mchenry': 'McHenry',
  'Will': 'Will'
};

/** Standard/official display spelling for a raw county name from the dataset. */
export function normalizeCountyDisplayName(rawCounty) {
  return COUNTY_DISPLAY_NAMES[rawCounty] || rawCounty;
}

/**
 * Approved ZIP codes for a city/mailing name, exact case-insensitive match
 * only (so "Aurora" never also matches "North Aurora"). Sorted ascending.
 */
export function getApprovedZipsForCity(cityName) {
  const target = cityName.trim().toLowerCase();
  return Object.entries(serviceAreaByZip)
    .filter(([, info]) => info.city.toLowerCase() === target)
    .map(([zip]) => zip)
    .sort();
}

/**
 * Approved counties (display-normalized, deduplicated, alphabetical) a city's
 * approved ZIP codes fall into.
 */
export function getApprovedCountiesForCity(cityName) {
  const zips = getApprovedZipsForCity(cityName);
  const counties = new Set(zips.map((zip) => normalizeCountyDisplayName(serviceAreaByZip[zip].county)));
  return [...counties].sort();
}

/** Every county (display-normalized, deduplicated, alphabetical) present anywhere in the approved dataset. */
export function getAllApprovedCounties() {
  const counties = new Set(Object.values(serviceAreaByZip).map((info) => normalizeCountyDisplayName(info.county)));
  return [...counties].sort();
}
